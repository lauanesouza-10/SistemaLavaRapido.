    private void btnCadastrarServicoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarServicoActionPerformed
    
try {
    String nome = txtNomeServico.getText().trim();
    String descricao = txtDescricao.getText().trim();

    String valor = txtPreco.getText().trim()
            .replace("R$", "")
            .replace(".", "")
            .replace(",", ".");

    BigDecimal preco = new BigDecimal(valor);

    tipoServicoService.cadastrar(nome, descricao, preco);

    JOptionPane.showMessageDialog(
        this, "Servico cadastrado com sucesso!"
    );

    txtNomeServico.setText("");
    txtDescricao.setText("");
    txtPreco.setText("");

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(
        this, "Informe um preco valido. Exemplo: 60,00"
    );
} catch (IllegalArgumentException e) {
    JOptionPane.showMessageDialog(
        this, e.getMessage()
    );
}

    }//GEN-LAST:event_btnCadastrarServicoActionPerformed

    private void btnListarServicoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnListarServicoActionPerformed
    
StringBuilder lista = new StringBuilder();

for (br.com.lavarapido.model.TipoServico servico :
        tipoServicoService.listar()) {

    lista.append("ID: ").append(servico.getId())
         .append("\nServico: ").append(servico.getNome())
         .append("\nDescricao: ").append(servico.getDescricao())
         .append("\nPreco: R$ ")
         .append(servico.getPreco().toString().replace(".", ","))
         .append("\n-------------------------\n");
}

if (lista.length() == 0) {
    JOptionPane.showMessageDialog(
        this,
        "Nenhum servico cadastrado."
    );
} else {
    JOptionPane.showMessageDialog(
        this,
        lista.toString(),
        "Servicos cadastrados",
        JOptionPane.INFORMATION_MESSAGE
    );
}

    }//GEN-LAST:event_btnListarServicoActionPerformed

