    private void btnAgendarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgendarActionPerformed
    
try {
    if (comboCliente.getSelectedItem() == null ||
        comboServico.getSelectedItem() == null) {

        JOptionPane.showMessageDialog(
                this,
                "Cadastre um cliente e um servico antes de agendar."
        );
        return;
    }

    int idCliente = Integer.parseInt(
            comboCliente.getSelectedItem().toString()
                    .split(" - ", 2)[0]
    );

    int idServico = Integer.parseInt(
            comboServico.getSelectedItem().toString()
                    .split(" - ", 2)[0]
    );

    Cliente cliente =
            DadosSistema.CLIENTES.buscarPorId(idCliente);

    TipoServico servico =
            DadosSistema.SERVICOS.buscarPorId(idServico);

    if (cliente == null || servico == null) {
        throw new IllegalArgumentException(
                "Cliente ou servico nao encontrado."
        );
    }

    DateTimeFormatter formato =
            DateTimeFormatter.ofPattern("dd/MM/uuuu HH:mm")
                    .withResolverStyle(ResolverStyle.STRICT);

    LocalDateTime dataHora = LocalDateTime.parse(
            txtData.getText().trim() + " "
                    + txtHorario.getText().trim(),
            formato
    );

    Agendamento agendamento =
            DadosSistema.AGENDAMENTOS.agendar(
                    cliente, servico, dataHora
            );
    atualizarTabela();
    JOptionPane.showMessageDialog(
            this,
            "Agendamento realizado com sucesso!\n"
                    + "ID: " + agendamento.getId()
    );

    txtData.setText("");
    txtHorario.setText("");

} catch (DateTimeParseException e) {
    JOptionPane.showMessageDialog(
            this,
            "Data ou horario invalido.\n"
                    + "Use dd/MM/aaaa e HH:mm."
    );
} catch (IllegalArgumentException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}

    }//GEN-LAST:event_btnAgendarActionPerformed

    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
    atualizarTabela();
StringBuilder lista = new StringBuilder();

DateTimeFormatter formato =
        DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm");

for (Agendamento agendamento :
        DadosSistema.AGENDAMENTOS.listar()) {

    lista.append("ID: ")
            .append(agendamento.getId())
            .append("\nCliente: ")
            .append(agendamento.getCliente().getNome())
            .append("\nServico: ")
            .append(agendamento.getTipoServico().getNome())
            .append("\nData/Hora: ")
            .append(agendamento.getDataHora().format(formato))
            .append("\nStatus: ")
            .append(agendamento.getStatus())
            .append("\n-------------------------\n");
}

if (lista.length() == 0) {
    JOptionPane.showMessageDialog(
            this, "Nenhum agendamento cadastrado."
    );
} else {
    JOptionPane.showMessageDialog(
            this,
            lista.toString(),
            "Agenda de Servicos",
            JOptionPane.INFORMATION_MESSAGE
    );
}

    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnEditarAgendamentoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarAgendamentoActionPerformed
    
try {
    String entrada = JOptionPane.showInputDialog(
            this,
            "Digite o ID do agendamento que deseja editar:"
    );

    if (entrada == null) {
        return;
    }

    int id = Integer.parseInt(entrada.trim());

    Agendamento agendamento =
            DadosSistema.AGENDAMENTOS.buscarPorId(id);

    if (agendamento == null) {
        JOptionPane.showMessageDialog(
                this, "Agendamento nao encontrado."
        );
        return;
    }

    if ("CANCELADO".equals(agendamento.getStatus())) {
        JOptionPane.showMessageDialog(
                this, "Nao e possivel editar um agendamento cancelado."
        );
        return;
    }

    DateTimeFormatter formato =
            DateTimeFormatter.ofPattern("dd/MM/uuuu HH:mm")
                    .withResolverStyle(ResolverStyle.STRICT);

    String dataAtual = agendamento.getDataHora()
            .format(DateTimeFormatter.ofPattern("dd/MM/yyyy"));

    String horaAtual = agendamento.getDataHora()
            .format(DateTimeFormatter.ofPattern("HH:mm"));

    String novaData = JOptionPane.showInputDialog(
            this, "Nova data:", dataAtual
    );

    if (novaData == null) {
        return;
    }

    String novoHorario = JOptionPane.showInputDialog(
            this, "Novo horario:", horaAtual
    );

    if (novoHorario == null) {
        return;
    }

    LocalDateTime novaDataHora = LocalDateTime.parse(
            novaData.trim() + " " + novoHorario.trim(),
            formato
    );

    DadosSistema.AGENDAMENTOS.editar(
            id,
            agendamento.getCliente(),
            agendamento.getTipoServico(),
            novaDataHora
    );
    atualizarTabela();

    JOptionPane.showMessageDialog(
            this, "Agendamento atualizado com sucesso!"
    );

} catch (DateTimeParseException e) {
    JOptionPane.showMessageDialog(
            this, "Data ou horario invalido."
    );
} catch (IllegalArgumentException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}

    }//GEN-LAST:event_btnEditarAgendamentoActionPerformed

    private void btnCancelarAgendamentoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelarAgendamentoActionPerformed
    
try {
    String entrada = JOptionPane.showInputDialog(
            this,
            "Digite o ID do agendamento que deseja cancelar:"
    );

    if (entrada == null) {
        return;
    }

    int id = Integer.parseInt(entrada.trim());

    Agendamento agendamento =
            DadosSistema.AGENDAMENTOS.buscarPorId(id);

    if (agendamento == null) {
        JOptionPane.showMessageDialog(
                this, "Agendamento nao encontrado."
        );
        return;
    }

    if ("CANCELADO".equals(agendamento.getStatus())) {
        JOptionPane.showMessageDialog(
                this, "Este agendamento ja esta cancelado."
        );
        return;
    }

    int confirmar = JOptionPane.showConfirmDialog(
            this,
            "Deseja cancelar o agendamento " + id + "?",
            "Confirmar cancelamento",
            JOptionPane.YES_NO_OPTION
    );

    if (confirmar == JOptionPane.YES_OPTION) {
        DadosSistema.AGENDAMENTOS.cancelar(id);
        
        atualizarTabela();

        JOptionPane.showMessageDialog(
                this, "Agendamento cancelado com sucesso!"
        );
    }

} catch (IllegalArgumentException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}

    }//GEN-LAST:event_btnCancelarAgendamentoActionPerformed

