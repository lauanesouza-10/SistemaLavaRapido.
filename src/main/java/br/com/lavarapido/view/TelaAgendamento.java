private void carregarCombos() {

        System.out.println("Clientes cadastrados: "
                + DadosSistema.CLIENTES.listar().size());

        System.out.println("Servicos cadastrados: "
                + DadosSistema.SERVICOS.listar().size());

        comboCliente.removeAllItems();
        comboServico.removeAllItems();

        for (Cliente cliente : DadosSistema.CLIENTES.listar()) {
            comboCliente.addItem(
                    cliente.getId() + " - " + cliente.getNome()
            );
        }

        for (TipoServico servico : DadosSistema.SERVICOS.listar()) {
            comboServico.addItem(
                    servico.getId() + " - " + servico.getNome()
            );
        }
    }


private void atualizarTabela() {

    DefaultTableModel modelo = new DefaultTableModel(
        new Object[]{"ID", "Cliente", "Serviço", "Data/Hora", "Status"},
        0
    ) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };

    DateTimeFormatter formato =
        DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm");

    for (Agendamento agendamento : DadosSistema.AGENDAMENTOS.listar()) {

        modelo.addRow(new Object[]{
            agendamento.getId(),
            agendamento.getCliente().getNome(),
            agendamento.getTipoServico().getNome(),
            agendamento.getDataHora().format(formato),
            agendamento.getStatus()
        });
    }

    tabelaAgendamentos.setModel(modelo);
}


