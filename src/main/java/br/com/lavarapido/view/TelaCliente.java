    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
    
StringBuilder lista = new StringBuilder();

for (br.com.lavarapido.model.Cliente cliente :
        clienteService.listar()) {

    lista.append("ID: ").append(cliente.getId())
         .append("\nNome: ").append(cliente.getNome())
         .append("\nCPF: ").append(cliente.getCpf())
         .append("\nTelefone: ").append(cliente.getTelefone())
         .append("\nE-mail: ").append(cliente.getEmail())
         .append("\nPlaca: ").append(cliente.getPlacaVeiculo())
         .append("\n-------------------------\n");
}

if (lista.length() == 0) {
    JOptionPane.showMessageDialog(
        this, "Nenhum cliente cadastrado.");
} else {
    JOptionPane.showMessageDialog(
        this, lista.toString(),
        "Clientes cadastrados",
        JOptionPane.INFORMATION_MESSAGE
    );
}
    }//GEN-LAST:event_jButton4ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
     
try {
    String entrada = JOptionPane.showInputDialog(
        this, "Digite o ID do cliente que deseja editar:"
    );

    if (entrada == null) {
        return;
    }

    int id = Integer.parseInt(entrada.trim());

    br.com.lavarapido.model.Cliente cliente =
            clienteService.buscarPorId(id);

    if (cliente == null) {
        JOptionPane.showMessageDialog(
            this, "Cliente nao encontrado.");
        return;
    }

    txtNome.setText(cliente.getNome());
    txtCpf.setText(cliente.getCpf());
    txtTelefone.setText(cliente.getTelefone());
    txtEmail.setText(cliente.getEmail());
    txtPlaca.setText(cliente.getPlacaVeiculo());

    int confirmar = JOptionPane.showConfirmDialog(
        this,
        "Os dados atuais foram carregados.\n"
        + "Deseja informar os novos dados agora?",
        "Editar cliente",
        JOptionPane.YES_NO_OPTION
    );

    if (confirmar != JOptionPane.YES_OPTION) {
        return;
    }

    String nome = JOptionPane.showInputDialog(
        this, "Nome:", cliente.getNome());
    if (nome == null) return;

    String cpf = JOptionPane.showInputDialog(
        this, "CPF:", cliente.getCpf());
    if (cpf == null) return;

    String telefone = JOptionPane.showInputDialog(
        this, "Telefone:", cliente.getTelefone());
    if (telefone == null) return;

    String email = JOptionPane.showInputDialog(
        this, "E-mail:", cliente.getEmail());
    if (email == null) return;

    String placa = JOptionPane.showInputDialog(
        this, "Placa do veiculo:", cliente.getPlacaVeiculo());
    if (placa == null) return;

    clienteService.editar(
        id, nome.trim(), cpf.trim(),
        telefone.trim(), email.trim(), placa.trim()
    );

    txtNome.setText(nome);
    txtCpf.setText(cpf);
    txtTelefone.setText(telefone);
    txtEmail.setText(email);
    txtPlaca.setText(placa);

    JOptionPane.showMessageDialog(
        this, "Cliente atualizado com sucesso!"
    );

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(
        this, "Digite um ID numerico valido.");
} catch (IllegalArgumentException e) {
    JOptionPane.showMessageDialog(
        this, e.getMessage(), "Erro",
        JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
     
try {
    String entrada = JOptionPane.showInputDialog(
        this,
        "Digite o ID do cliente que deseja excluir:"
    );

    if (entrada == null) {
        return;
    }

    int id = Integer.parseInt(entrada.trim());

    if (clienteService.buscarPorId(id) == null) {
        JOptionPane.showMessageDialog(
            this,
            "Cliente nao encontrado!"
        );
        return;
    }

    int confirmar = JOptionPane.showConfirmDialog(
        this,
        "Deseja realmente excluir este cliente?",
        "Confirmar exclusao",
        JOptionPane.YES_NO_OPTION
    );

    if (confirmar == JOptionPane.YES_OPTION) {
        clienteService.excluir(id);

        JOptionPane.showMessageDialog(
            this,
            "Cliente excluido com sucesso!"
        );

        txtNome.setText("");
        txtCpf.setText("");
        txtTelefone.setText("");
        txtEmail.setText("");
        txtPlaca.setText("");
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(
        this,
        "Digite um ID numerico valido."
    );
} catch (IllegalArgumentException e) {
    JOptionPane.showMessageDialog(
        this,
        e.getMessage(),
        "Erro",
        JOptionPane.ERROR_MESSAGE
    );
}

    }//GEN-LAST:event_jButton3ActionPerformed

